fun main() {
    val sum: Int = 10 + 3
    val div: Int = 10 / 3
    val div2: Double = 10 / 3.0
    val rem: Int = 10 % 3

    println(sum)
    println(div)
    println(div2)
    println(rem)

    println("5 == 5: ${5 == 5}")
    println("5 != 3: ${5 != 3}")
    println("5 > 3: ${5 > 3}")

    println("true && false => ${true && false}")
    println("true || false => ${true || false}")
    println("!true => ${!true}")
}

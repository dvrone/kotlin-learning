fun main() {
    val a: Int = 42
    val b: Double  = 3.14
    val c: Long = 42L
    val d: Float = 3.14f
    val e: Boolean = true
    val f: Char = 'A'
    val g: String = "Hello, I'm Diyorbek!"

    println("Int: $a")
    println("Double: $b")
    println("Long: $c")
    println("Float: $d")
    println("Boolean: $e")
    println("Char: $f")
    println("String: $g")
}
